// Small helper for image placeholders (all use a data-URL SVG so they
// render offline without any external hits).
function placeholder(color, letter) {
  const svg =
    `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 200 200'>` +
    `<rect width='200' height='200' fill='${color}'/>` +
    `<text x='100' y='118' font-family='Georgia' font-size='72' font-weight='bold' text-anchor='middle' fill='#FFF'>${letter}</text>` +
    `</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

